#!/usr/bin/env node
/**
 * Writes mac-cloud/.env without bash-sourcing JSON (which breaks service accounts).
 * Usage: node mac-cloud/scripts/setup-migration-env.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';

const __dirname = dirname(fileURLToPath(import.meta.url));
const MAC_CLOUD = resolve(__dirname, '..');
const ROOT = resolve(MAC_CLOUD, '..');
const ROOT_ENV = resolve(ROOT, '.env');
const ENV_OUT = resolve(MAC_CLOUD, '.env');
const REGISTRY_SA = process.env.REGISTRY_SA_PATH
  || resolve(process.env.HOME || '', 'amlak-sale-product/license-api-server/service-account.json');

function readJsonEnv(name, fallback = '') {
  const value = process.env[name] || fallback;
  if (!value || !String(value).trim()) return '';
  try {
    return JSON.stringify(JSON.parse(String(value)));
  } catch {
    return String(value).trim();
  }
}

function readServiceAccountFromPath(path) {
  if (!path || !existsSync(path)) return '';
  try {
    return JSON.stringify(JSON.parse(readFileSync(path, 'utf8')));
  } catch {
    return '';
  }
}

if (!existsSync(ROOT_ENV)) {
  console.error(`Missing ${ROOT_ENV}`);
  process.exit(1);
}

dotenv.config({ path: ROOT_ENV });

const password = process.env.POSTGRES_PASSWORD || '';
if (!password) {
  console.error('POSTGRES_PASSWORD not set in root .env');
  process.exit(1);
}

const user = process.env.POSTGRES_USER || 'amlak';
const db = process.env.POSTGRES_DB || 'amlak';
const host = process.env.POSTGRES_HOST || 'localhost';
const port = process.env.POSTGRES_PORT || '5432';
const databaseUrl = `postgres://${user}:${password}@${host}:${port}/${db}`;

let firebaseSa = readJsonEnv('FIREBASE_SERVICE_ACCOUNT_JSON')
  || readJsonEnv('AMLAK_ADMIN_FIREBASE_SERVICE_ACCOUNT_JSON');
if (!firebaseSa) {
  firebaseSa = readServiceAccountFromPath(process.env.FIREBASE_SERVICE_ACCOUNT_PATH || '');
}
if (!firebaseSa) {
  console.warn('WARN: FIREBASE_SERVICE_ACCOUNT_JSON not found — add saudi-property-manager Admin SDK JSON before cutover.');
}

let licenseSa = readJsonEnv('LICENSE_REGISTRY_SERVICE_ACCOUNT_JSON')
  || readJsonEnv('AMLAK_SALES_SERVICE_ACCOUNT_JSON');
if (!licenseSa) {
  licenseSa = readServiceAccountFromPath(REGISTRY_SA);
  if (licenseSa) console.log(`Using registry SA: ${REGISTRY_SA}`);
} else {
  console.log('Using LICENSE_REGISTRY_SERVICE_ACCOUNT_JSON from root .env');
}

const buyerMap = readJsonEnv('BUYER_FIREBASE_PROJECTS_JSON', '{}') || '{}';
const bookMap = readJsonEnv('POSTGRES_BOOK_ID_MAP', '{}') || '{}';
const skipBuyerImport = String(process.env.SKIP_BUYER_FIREBASE_IMPORT || '').trim();

const lines = [
  '# Generated by setup-migration-env.mjs — DO NOT COMMIT',
  `DATABASE_URL=${databaseUrl}`,
];
if (firebaseSa) lines.push(`FIREBASE_SERVICE_ACCOUNT_JSON=${firebaseSa}`);
if (licenseSa) lines.push(`LICENSE_REGISTRY_SERVICE_ACCOUNT_JSON=${licenseSa}`);
lines.push(`BUYER_FIREBASE_PROJECTS_JSON=${buyerMap}`);
lines.push(`POSTGRES_BOOK_ID_MAP=${bookMap}`);
if (skipBuyerImport) lines.push(`SKIP_BUYER_FIREBASE_IMPORT=${skipBuyerImport}`);

writeFileSync(ENV_OUT, `${lines.join('\n')}\n`, { mode: 0o600 });
console.log(`Wrote ${ENV_OUT}`);
console.log('Next: cd mac-cloud && npm install && npm run migrate:inventory');
